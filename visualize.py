"""
Vembanad Lake: visualize one window's Sentinel-2 AOI data and computed indices.
One file, no project imports. Dependencies: rasterio, numpy, matplotlib
    pip install rasterio numpy matplotlib

Shows, for a single window (e.g. A):
  1. True-color-ish RGB composite (B04/B03/B02, stretched)
  2. SCL validity mask (cloud / shadow / nodata highlighted)
  3. NDTI (turbidity), NDCI (chlorophyll), NDSSI (suspended sediment),
     MNDWI (extra water mask) (only if indexGen.py produced them for
     this window -- if the window was flagged INSUFFICIENT, this script says
     so and skips those panels rather than pretending they exist)
  4. Concentration proxies CHLA (ug/L, Mishra 2012), SPM (mg/L, Nechad),
     TURB (FNU, Dogliotti blend) when present (global calibration, not
     Vembanad-validated; for relative A/B/C comparison).
  5. Discrete labels CHLA_CLASS / TURB_CLASS / SPM_CLASS / WQ_FLAG when
     present, plus a printed + saved stats table (valid pixels only).

Usage (from the project root, same --root as download.py / indexGen.py)
  python visualize_window.py --window A
  python visualize_window.py --window A --save data/indices/A_preview.png
  python visualize_window.py --window A --save data/indices/A_preview.png --stats data/indices/A_stats.json

  Cross-date change / hotspot heatmap over 2-3 windows (one more judge image):
  python visualize.py --compare ABC --save data/indices/change_ABC.png
  python visualize.py --compare ABC --hotspot-pct 10 --write-deltas
  python visualize.py --compare AB --change-products NDTI,NDCI,NDSSI,CHLA,SPM,TURB

  Seasonal story (Premonsoon -> Monsoon -> Postmonsoon, one judge image):
  python visualize.py --seasons ABC --save data/indices/seasons_ABC.png
  python visualize.py --seasons ABC --season-names Premonsoon,Monsoon,Postmonsoon
  python visualize.py --seasons ABC --season-metric CHLA --stats-only
  python visualize.py --seasons ABC --season-mode state
  (default --season-mode change: panel 1 = baseline state, later panels = Δ vs first season;
   land stays full-brightness satellite RGB, only water is dimmed + heatmapped)

  Low-memory cloud runs (process gets OOM-killed):
  python visualize.py --window A --stats-only
  python visualize.py --window A --save preview.png --display-max-dim 800 --dpi 80
  python visualize.py --compare ABC --save change.png --display-max-dim 800 --dpi 80
"""
