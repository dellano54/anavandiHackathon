def summarize(arr, max_sample=2_000_000):
    """NaN-aware summary over valid (finite) pixels. Memory-safe.

    mean/std/min/max/n are exact (single streaming pass, no big copies).
    median/p5/p95 use a strided sample when the array is huge (accurate to
    ~1e-4 for smooth index fields, avoids a 100MB+ sort of 20M+ pixels).
    """
    finite = np.isfinite(arr)
    n_valid = int(finite.sum())
    n_total = int(arr.size)
    if n_valid == 0:
        return {"n_valid": 0, "n_total": n_total, "mean": None, "median": None,
                "std": None, "min": None, "max": None, "p5": None, "p95": None}
    # Exact moments without materializing a copy: use masked ufuncs in float64.
    vals = arr.astype(np.float64, copy=False)
    s = np.nansum(vals)
    s2 = np.nansum(vals * vals)
    mean = s / n_valid
    var = max(s2 / n_valid - mean * mean, 0.0)
    out = {
        "n_valid": n_valid,
        "n_total": n_total,
        "mean": round(float(mean), 4),
        "median": None,
        "std": round(float(np.sqrt(var)), 4),
        "min": round(float(np.nanmin(vals)), 4),
        "max": round(float(np.nanmax(vals)), 4),
        "p5": None,
        "p95": None,
    }
    # Quantiles on a strided sample (exact when small).
    stride = max(1, int(np.ceil(n_valid / max_sample)))
    sample = vals[finite][::stride]
    out["median"] = round(float(np.median(sample)), 4)
    out["p5"] = round(float(np.percentile(sample, 5)), 4)
    out["p95"] = round(float(np.percentile(sample, 95)), 4)
    del sample
    return out


def decimate(arr, max_dim):
    """Nearest-neighbour stride downsample so max(h, w) <= max_dim. No-op if small."""
    h, w = arr.shape[:2]
    m = max(h, w)
    if m <= max_dim:
        return arr
    s = int(np.ceil(m / max_dim))
    return arr[::s, ::s].copy()


def read_capped(path, max_dim, dtype=np.float32, resampling=Resampling.bilinear):
    """Read a raster decimated to max_dim for display. Returns small array."""
    with rasterio.open(path) as src:
        h, w = src.height, src.width
        m = max(h, w)
        if m <= max_dim:
            return src.read(1).astype(dtype, copy=False)
        s = int(np.ceil(m / max_dim))
        return src.read(1, out_shape=(int(np.ceil(h / s)), int(np.ceil(w / s))),
                        resampling=resampling).astype(dtype, copy=False)


def dilate_mask(mask, iters):
    """8-neighbour binary dilation without scipy (for --water-expand)."""
    out = mask.copy()
    for _ in range(max(0, int(iters))):
        padded = np.pad(out, 1, mode="constant", constant_values=False)
        grown = np.zeros_like(out)
        for dr in (-1, 0, 1):
            for dc in (-1, 0, 1):
                grown |= padded[1 + dr:1 + dr + out.shape[0], 1 + dc:1 + dc + out.shape[1]]
        out = grown
    return out


def dim_rgb(rgb, dim):
    """Dim an RGB float image for use UNDER the water heatmap (dim in 0..1)."""
    d = float(dim)
    d = min(1.0, max(0.0, d))
    return (rgb * d).astype(np.float32)


def paint_basemap(ax, rgb_bright, base_dim, water_disp):
    """Land at full satellite brightness; only water is dimmed for heatmap contrast.

    rgb_bright: display-size RGB float image (H, W, 3). water_disp: display-size
    bool mask (True = water). Land pixels keep full brightness; water pixels get
    dimmed so the heatmap on top reads clearly.
    """
    ax.imshow(rgb_bright)
    d = min(1.0, max(0.0, float(base_dim)))
    if water_disp is not None and d < 1.0:
        dim = dim_rgb(rgb_bright, d)
        mask3d = np.broadcast_to(~water_disp[:, :, None], dim.shape)
        ax.imshow(np.ma.masked_where(mask3d, dim))


def label_fractions(cls_arr, names):
    valid = cls_arr[cls_arr > 0]
    n_valid = int(valid.size)
    fractions = {}
    for code, name in enumerate(names):
        if code == 0:
            continue
        cnt = int((cls_arr == code).sum())
        fractions[name] = round(100.0 * cnt / n_valid, 2) if n_valid else 0.0
    dominant = max(fractions, key=fractions.get) if fractions and n_valid else None
    return {"n_valid": n_valid, "fractions_pct": fractions, "dominant": dominant}


def common_grid(tile_infos):
    tb = tile_infos[0]["target_bounds"]
    x0, y0, x1, y1 = tb
    w10 = int(round((x1 - x0) / 10))
    h10 = int(round((y1 - y0) / 10))
    transform10 = Affine(10, 0, x0, 0, -10, y1)
    w20, h20 = w10 // 2, h10 // 2
    transform20 = Affine(20, 0, x0, 0, -20, y1)
    return (transform10, (h10, w10)), (transform20, (h20, w20))


def mosaic_tiles(paths, out_transform, out_shape, dtype, nodata_fill=0):
    canvas = np.full(out_shape, nodata_fill, dtype=dtype)
    for p in paths:
        with rasterio.open(p) as src:
            src_arr = src.read(1)
            dst = np.full(out_shape, nodata_fill, dtype=dtype)
            reproject(source=src_arr, destination=dst,
                      src_transform=src.transform, src_crs=src.crs,
                      dst_transform=out_transform, dst_crs=src.crs,
                      resampling=Resampling.nearest, src_nodata=nodata_fill, dst_nodata=nodata_fill)
            valid = dst != nodata_fill
            canvas[valid] = dst[valid]
    return canvas


def upsample_20m_to_10m(arr20, shape10):
    h10, w10 = shape10
    out = np.repeat(np.repeat(arr20, 2, axis=0), 2, axis=1)
    return out[:h10, :w10]


def stretch(band, lo=2, hi=98, exclude=None):
    """Percentile stretch. exclude (bool, same shape) removes pixels — typically
    clouds/shadows — from the percentile sample so they don't crush land brightness.
    Excluded pixels still render (clipped), they just don't set the black/white points."""
    sample = band[::8, ::8]
    if exclude is not None:
        excl = exclude[::8, ::8] if exclude.shape == band.shape else exclude
        valid = sample[(sample > 0) & ~excl]
    else:
        valid = sample[sample > 0]
    if valid.size == 0:
        return np.zeros_like(band, dtype=np.float32)
    p_lo, p_hi = np.percentile(valid, [lo, hi])
    del sample, valid
    out = np.clip((band.astype(np.float32) - p_lo) / max(p_hi - p_lo, 1e-6), 0, 1)
    out[band == 0] = 0
    return out


