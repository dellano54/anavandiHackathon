def breaks_tag(breaks_dict, class_key):
    """Short 'b1/b2/b3' tag for a label class panel title."""
    if class_key == "WQ_FLAG":
        return "mean-of-3"
    b = breaks_dict.get(CLASS_BREAK_KEY.get(class_key, ""), [])
    return "/".join(f"{x:g}" for x in b) if b else "n/a"


